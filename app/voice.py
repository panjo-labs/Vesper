"""
ElevenLabs turns the script into a voice.

We ask for character-level timestamps so the transcript lights up on the real
word, not an estimate. If that endpoint is unavailable on your account or
changes shape, we fall back to plain audio plus timings estimated from word
length. The fallback drifts a little on long shows, and the response says so
rather than pretending otherwise.
"""

from __future__ import annotations

import base64
import logging
import os
import re

import httpx

log = logging.getLogger("nightjar.voice")

BASE = "https://api.elevenlabs.io/v1/text-to-speech"
API_KEY = os.environ.get("ELEVENLABS_API_KEY", "")
# Override in the Space settings once you've picked a voice you like.
VOICE_ID = os.environ.get("ELEVENLABS_VOICE_ID", "JBFqnCBsd6RMkjVDRZzb")
MODEL_ID = os.environ.get("ELEVENLABS_MODEL", "eleven_turbo_v2_5")

WORD_RE = re.compile(r"\S+")


class VoiceError(RuntimeError):
    pass


def _settings() -> dict:
    # Low style and generous stability: this voice should sound like someone
    # reading to you in a quiet room, not performing.
    return {
        "stability": 0.55,
        "similarity_boost": 0.75,
        "style": 0.0,
        "use_speaker_boost": True,
    }


def _estimate(script: str, total: float) -> list[dict]:
    """Fallback timings. Longer words get proportionally more time."""
    words = WORD_RE.findall(script)
    weights = [len(w) + 1 for w in words]
    unit = total / max(1, sum(weights))
    out, t = [], 0.0
    for w, wt in zip(words, weights):
        out.append({"word": w, "start": round(t, 3)})
        t += wt * unit
    return out


def _align_to_words(script: str, chars: list[str], starts: list[float]) -> list[dict]:
    """Collapse per-character timings into per-word start times."""
    out: list[dict] = []
    pos = 0
    for m in WORD_RE.finditer(script):
        # Walk the character stream to the start of this word.
        while pos < len(chars) and chars[pos].isspace():
            pos += 1
        if pos >= len(starts):
            break
        out.append({"word": m.group(0), "start": round(float(starts[pos]), 3)})
        pos += len(m.group(0))
    return out


async def speak(script: str, timeout: float = 180.0) -> dict:
    if not API_KEY:
        raise VoiceError("ELEVENLABS_API_KEY is not set.")

    body = {
        "text": script,
        "model_id": MODEL_ID,
        "voice_settings": _settings(),
    }
    headers = {"xi-api-key": API_KEY, "Content-Type": "application/json"}

    async with httpx.AsyncClient(timeout=timeout) as client:
        # Preferred path: audio plus character timings in one response.
        try:
            r = await client.post(
                f"{BASE}/{VOICE_ID}/with-timestamps", headers=headers, json=body
            )
            if r.status_code == 200:
                d = r.json()
                al = d.get("alignment") or d.get("normalized_alignment") or {}
                chars = al.get("characters") or []
                starts = al.get("character_start_times_seconds") or []
                audio_b64 = d["audio_base64"]
                if chars and starts and len(chars) == len(starts):
                    return {
                        "audio_b64": audio_b64,
                        "words": _align_to_words(script, chars, starts),
                        "timing": "exact",
                    }
                log.warning("Timestamp payload was not usable; estimating instead.")
                return {
                    "audio_b64": audio_b64,
                    "words": _estimate(script, len(script.split()) / 2.2),
                    "timing": "estimated",
                }
            log.warning("with-timestamps returned %s; falling back.", r.status_code)
        except (httpx.HTTPError, KeyError, ValueError) as exc:
            log.warning("with-timestamps unavailable (%s); falling back.", exc)

        r = await client.post(f"{BASE}/{VOICE_ID}", headers=headers, json=body)

    if r.status_code == 401:
        raise VoiceError("ElevenLabs rejected the key.")
    if r.status_code == 402:
        raise VoiceError(
            "ElevenLabs wants a paid plan for this voice. Pick a premade voice."
        )
    if r.status_code == 429:
        raise VoiceError("ElevenLabs quota is exhausted for now.")
    if r.status_code >= 400:
        raise VoiceError(f"ElevenLabs returned {r.status_code}.")

    return {
        "audio_b64": base64.b64encode(r.content).decode("ascii"),
        "words": _estimate(script, len(script.split()) / 2.2),
        "timing": "estimated",
    }



# ── ambient bed ──────────────────────────────────────────────
# One loop per mood, generated by ElevenLabs once and kept on disk. After the
# first show in each mood it costs nothing, ever. Lazy on purpose.
AMBIENT_DIR = os.environ.get(
    "AMBIENT_DIR", os.path.join(os.path.dirname(__file__), "..", ".cache", "ambient")
)
AMBIENT_PROMPTS = {
    "tideline": "slow waves on a quiet shore at night, soft and distant, seamless loop, no voices",
    "deepfield": "low warm space ambience, gentle hum, faint shimmer, calm, seamless loop, no melody",
    "ember": "small fireplace crackling softly in a quiet room, distant rain, seamless loop",
}


async def ambient(mood: str, timeout: float = 120.0) -> str:
    """Return a path to this mood's loop, generating it the first time."""
    if mood not in AMBIENT_PROMPTS:
        raise VoiceError(f"No ambient bed for {mood!r}.")
    path = os.path.join(AMBIENT_DIR, f"{mood}.mp3")
    if os.path.exists(path):
        return path
    if not API_KEY:
        raise VoiceError("ELEVENLABS_API_KEY is not set.")

    async with httpx.AsyncClient(timeout=timeout) as client:
        r = await client.post(
            "https://api.elevenlabs.io/v1/sound-generation",
            headers={"xi-api-key": API_KEY, "Content-Type": "application/json"},
            json={
                "text": AMBIENT_PROMPTS[mood],
                "duration_seconds": 22,
                "prompt_influence": 0.4,
            },
        )
    if r.status_code != 200:
        # Most often the key lacks the sound_generation permission. The show
        # still plays, just without the bed underneath.
        raise VoiceError(f"ElevenLabs sound generation returned {r.status_code}.")

    os.makedirs(AMBIENT_DIR, exist_ok=True)
    with open(path, "wb") as f:
        f.write(r.content)
    return path
